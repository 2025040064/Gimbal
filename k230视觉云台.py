def digit_mask(gray, rect):
    x, y, width, height = rect
    # Four samples per cell reduce aliasing on thin strokes.
    columns = [
        (x + (4 * column + 1) * width // (4 * DIGIT_COLUMNS),
         x + (4 * column + 3) * width // (4 * DIGIT_COLUMNS))
        for column in range(DIGIT_COLUMNS)
    ]
    rows = []
    pixel = gray.get_pixel
    for row_index in range(DIGIT_ROWS):
        y0 = y + (4 * row_index + 1) * height // (4 * DIGIT_ROWS)
        y1 = y + (4 * row_index + 3) * height // (4 * DIGIT_ROWS)
        mask = 0
        for x0, x1 in columns:
            dark = (pixel(x0, y0) <= BLACK_MAX) + (pixel(x1, y0) <= BLACK_MAX)
            dark += (pixel(x0, y1) <= BLACK_MAX) + (pixel(x1, y1) <= BLACK_MAX)
            mask = (mask << 1) | (dark >= 2)
        rows.append(mask)
    return rows


def recognize_digit(gray, rect):
    rows = digit_mask(gray, rect)
    ratio = rect[2] * 100 // rect[3]
    best_id = None
    best_distance = second_distance = MAX_MATCH_DISTANCE + MIN_MATCH_MARGIN

    for digit, templates in enumerate(DIGIT_TEMPLATES):
        digit_distance = second_distance
        for template in templates:
            distance = abs(ratio - template[0]) // 3
            for row_index, row in enumerate(rows, 1):
                different = row ^ template[row_index]
                distance += BIT_COUNTS[different & 0xFF] + BIT_COUNTS[different >> 8]
                if distance >= digit_distance:
                    break
            digit_distance = min(distance, digit_distance)

        if digit_distance < best_distance:
            best_id = digit
            second_distance, best_distance = best_distance, digit_distance
        elif digit_distance < second_distance:
            second_distance = digit_distance

    if best_distance <= MAX_MATCH_DISTANCE and second_distance - best_distance >= MIN_MATCH_MARGIN:
        return best_id
    return None


def glyph_box(gray, card):
    x, y, width, height = card
    inset_x = max(1, width // 12)
    inset_y = max(1, height // 12)
    left, top = x + inset_x, y + inset_y
    right, bottom = x + width - inset_x, y + height - inset_y
    blobs = gray.find_blobs(
        [(0, BLACK_MAX)], roi=(left, top, right - left, bottom - top),
        x_stride=1, y_stride=1, pixels_threshold=12, area_threshold=24
    )
    if not blobs:
        return None

    glyph = max(blobs, key=lambda blob: blob.pixels())
    gx, gy, gw, gh = glyph.rect()
    # A clipped stroke or a second sizable mark makes the card ambiguous.
    if (gw < 4 or gh < MIN_GLYPH_HEIGHT or gh * 5 < height * 2
            or gx <= left or gy <= top or gx + gw >= right or gy + gh >= bottom):
        return None
    if any(other is not glyph and other.pixels() * 4 >= glyph.pixels() for other in blobs):
        return None
    return gx, gy, gw, gh


def detect_cards(gray):
    blobs = gray.find_blobs(
        [(WHITE_MIN, 255)], x_stride=3, y_stride=2,
        pixels_threshold=110, area_threshold=MIN_CARD_SIDE * MIN_CARD_SIDE
    )
    cards = []
    for blob in blobs:
        x, y, width, height = blob.rect()
        if (min(width, height) < MIN_CARD_SIDE
                or max(width, height) > 3 * min(width, height)
                or x == 0 or y == 0 or x + width >= DETECT_WIDTH or y + height >= DETECT_HEIGHT
                or blob.pixels() * 2 < width * height):
            continue
        cards.append(blob)

    cards.sort(key=lambda blob: blob.pixels(), reverse=True)
    detections = []
    for card in cards[:MAX_CARDS_PER_FRAME]:
        rect = card.rect()
        glyph = glyph_box(gray, rect)
        if glyph is not None:
            digit = recognize_digit(gray, glyph)
            if digit is not None:
                detections.append((digit, rect))
    return detections


def center(rect):
    x, y, width, height = rect
    return x + width // 2, y + height // 2


def nearby(previous, current):
    old_x, old_y = center(previous)
    new_x, new_y = center(current)
    return (abs(new_x - old_x) <= max(previous[2], current[2])
            and abs(new_y - old_y) <= max(previous[3], current[3]))


class CommandReader:
    def __init__(self):
        self.line = bytearray()
        self.discard = False

    def feed(self, data):
        for value in data or b"":
            if value == 10:
                if self.line and not self.discard:
                    line = bytes(self.line)
                    yield line[:-1] if line.endswith(b"\r") else line
                self.line = bytearray()
                self.discard = False
            elif not self.discard:
                if len(self.line) < 8:
                    self.line.append(value)
                else:
                    self.discard = True


class VisionSession:
    def __init__(self, ticks_diff):
        self.ticks_diff = ticks_diff
        self.target_id = None
        self.scan_started = None
        self.seen = set()
        self.streaks = {}

    def command(self, line, now):
        if line == b"SCAN":
            self.scan_started = now
            self.seen.clear()
            self.target_id = None
        elif line == b"STOP":
            self.scan_started = None
            self.target_id = None
        elif len(line) == 4 and line[:3] == b"ID," and 48 <= line[3] <= 57:
            target_id = line[3] - 48
            if target_id == self.target_id:
                return True
            self.target_id = target_id
            self.scan_started = None
        else:
            return False
        self.streaks = {}
        return True

    def observe(self, detections, now):
        scan_result = None
        if self.scan_started is not None and self.ticks_diff(now, self.scan_started) >= SCAN_DURATION_MS:
            scan_result = tuple(sorted(self.seen))
            self.scan_started = None

        by_id = {}
        duplicates = set()
        for digit, rect in detections:
            if digit in by_id:
                duplicates.add(digit)
            by_id[digit] = rect

        confirmed = {}
        streaks = {}
        for digit, rect in by_id.items():
            if digit in duplicates:
                continue
            previous = self.streaks.get(digit)
            count = 1
            if previous is not None and nearby(previous[0], rect):
                count = min(CONFIRM_FRAMES, previous[1] + 1)
            streaks[digit] = (rect, count)
            if count == CONFIRM_FRAMES:
                confirmed[digit] = rect
        self.streaks = streaks

        new_ids = ()
        if self.scan_started is not None:
            new_ids = tuple(sorted(set(confirmed) - self.seen))
            self.seen.update(new_ids)
        return confirmed, new_ids, scan_result


def coordinate_frame(rect):
    if rect is None:
        return NO_TARGET_FRAME
    cx, cy = center(rect)
    payload = "{},{},{},{},{},{}".format(
        DETECT_WIDTH, DETECT_HEIGHT, cx, cy, rect[2], rect[3]
    )
    return FRAME_HEADER + payload.encode() + FRAME_TAIL


def send_coordinates(uart, rect):
    frame = coordinate_frame(rect)
    sent = uart.write(frame)
    if sent != len(frame):
        raise OSError("UART2 short write: {} of {}".format(sent, len(frame)))


def draw_overlay(frame, confirmed, target_id):
    for digit, rect in confirmed.items():
        color = (0, 255, 0) if digit == target_id else (255, 255, 0)
        frame.draw_rectangle(rect, color=color, thickness=2)
        frame.draw_string(rect[0], max(0, rect[1] - 18), str(digit), color=color, scale=2)
    if target_id in confirmed:
        cx, cy = center(confirmed[target_id])
        frame.draw_cross(cx, cy, color=(0, 255, 0))


def cleanup(action, *args):
    try:
        action(*args)
    except Exception as error:
        print("CLEANUP_ERROR", error)


def main():
    import image
    import os
    import time
    from machine import FPIOA, UART
    from media.display import Display
    from media.media import MediaManager
    from media.sensor import Sensor

    if INITIAL_TARGET_ID is not None and (
        type(INITIAL_TARGET_ID) is not int or not 0 <= INITIAL_TARGET_ID <= 9
    ):
        raise ValueError("INITIAL_TARGET_ID must be None or a digit from 0 to 9")

    uart = sensor = None
    display_ready = media_ready = False
    try:
        fpioa = FPIOA()
        fpioa.set_function(UART2_TX_PIN, FPIOA.UART2_TXD)
        fpioa.set_function(UART2_RX_PIN, FPIOA.UART2_RXD)
        uart = UART(
            UART.UART2, baudrate=115200, bits=UART.EIGHTBITS,
            parity=UART.PARITY_NONE, stop=UART.STOPBITS_ONE
        )

        sensor = Sensor(width=DETECT_WIDTH, height=DETECT_HEIGHT)
        sensor.reset()
        sensor.set_vflip(VFLIP)  
        sensor.set_hmirror(HMIRROR)

        sensor.set_framesize(width=DETECT_WIDTH, height=DETECT_HEIGHT)
        sensor.set_pixformat(Sensor.RGB565)

        Display.init(
            Display.VIRT, width=DETECT_WIDTH, height=DETECT_HEIGHT, fps=30, to_ide=True
        )
        display_ready = True
        MediaManager.init()
        media_ready = True
        gray = image.Image(DETECT_WIDTH, DETECT_HEIGHT, image.GRAYSCALE)
        sensor.run()

        reader = CommandReader()
        session = VisionSession(time.ticks_diff)
        last_send = None
        tracked_id = None
        if INITIAL_TARGET_ID is not None:
            session.command("ID,{}".format(INITIAL_TARGET_ID).encode(), time.ticks_ms())
        print("READY UART2 115200 8N1. Commands: SCAN, ID,0-9, STOP (LF or CRLF).")

        while True:
            os.exitpoint()
            for command in reader.feed(uart.read(32)):
                now = time.ticks_ms()
                previous_id = session.target_id
                if session.command(command, now):
                    print("COMMAND", command.decode())
                    if previous_id is not None and previous_id != session.target_id:
                        send_coordinates(uart, None)
                        last_send = now
                else:
                    print("INVALID_COMMAND")

            frame = sensor.snapshot()
            gray.draw_image(frame, 0, 0)
            detections = detect_cards(gray)
            now = time.ticks_ms()
            confirmed, new_ids, scan_result = session.observe(detections, now)
            selected = confirmed.get(session.target_id)
            if last_send is None or time.ticks_diff(now, last_send) >= SEND_INTERVAL_MS:
                send_coordinates(uart, selected)
                last_send = now

            active_id = session.target_id if selected is not None else None
            if tracked_id != active_id:
                if tracked_id is not None:
                    print("LOST,{}".format(tracked_id))
                if active_id is not None:
                    print("TRACK,{}".format(active_id))
                tracked_id = active_id
            for digit in new_ids:
                print("FOUND,{}".format(digit))
            if scan_result is not None:
                print("SCAN_RESULT,{}".format(",".join([str(digit) for digit in scan_result])))

            draw_overlay(frame, confirmed, session.target_id)
            Display.show_image(frame)

    except KeyboardInterrupt:
        print("STOPPED")
    finally:
        if uart is not None:
            cleanup(send_coordinates, uart, None)
            cleanup(uart.deinit)
        if sensor is not None:
            cleanup(sensor.stop)
        if display_ready:
            cleanup(Display.deinit)
        if media_ready:
            os.exitpoint(os.EXITPOINT_ENABLE_SLEEP)
            time.sleep_ms(100)
            cleanup(MediaManager.deinit)


if __name__ == "__main__":
    main()
