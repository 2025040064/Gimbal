def digit_mask(gray, rect):
    x, y, width, height = rect
    # Four samples per cell reduce aliasing on thin strokes.
    columns = [
        (x + (4 * column + 1) * width // (4 * DIGIT_COLUMNS),
         x + (4 * column + 3) * width // (4 * DIGIT_COLUMNS))
        for column in range(DIGIT_COLUMNS)
    ]
    rows = []
    pixel = gray.get_pixel
    for row_index in range(DIGIT_ROWS):
        y0 = y + (4 * row_index + 1) * height // (4 * DIGIT_ROWS)
        y1 = y + (4 * row_index + 3) * height // (4 * DIGIT_ROWS)
        mask = 0
        for x0, x1 in columns:
            dark = (pixel(x0, y0) <= BLACK_MAX) + (pixel(x1, y0) <= BLACK_MAX)
            dark += (pixel(x0, y1) <= BLACK_MAX) + (pixel(x1, y1) <= BLACK_MAX)
            mask = (mask << 1) | (dark >= 2)
        rows.append(mask)
    return rows


def recognize_digit(gray, rect):
    rows = digit_mask(gray, rect)
    ratio = rect[2] * 100 // rect[3]
    best_id = None
    best_distance = second_distance = MAX_MATCH_DISTANCE + MIN_MATCH_MARGIN

    for digit, templates in enumerate(DIGIT_TEMPLATES):
        digit_distance = second_distance
        for template in templates:
            distance = abs(ratio - template[0]) // 3
            for row_index, row in enumerate(rows, 1):
                different = row ^ template[row_index]
                distance += BIT_COUNTS[different & 0xFF] + BIT_COUNTS[different >> 8]
                if distance >= digit_distance:
                    break
            digit_distance = min(distance, digit_distance)

        if digit_distance < best_distance:
            best_id = digit
            second_distance, best_distance = best_distance, digit_distance
        elif digit_distance < second_distance:
            second_distance = digit_distance

    if best_distance <= MAX_MATCH_DISTANCE and second_distance - best_distance >= MIN_MATCH_MARGIN:
        return best_id
    return None


def glyph_box(gray, card):
    x, y, width, height = card
    inset_x = max(1, width // 12)
    inset_y = max(1, height // 12)
    left, top = x + inset_x, y + inset_y
    right, bottom = x + width - inset_x, y + height - inset_y
    blobs = gray.find_blobs(
        [(0, BLACK_MAX)], roi=(left, top, right - left, bottom - top),
        x_stride=1, y_stride=1, pixels_threshold=12, area_threshold=24
    )
    if not blobs:
        return None

    glyph = max(blobs, key=lambda blob: blob.pixels())
    gx, gy, gw, gh = glyph.rect()
    # A clipped stroke or a second sizable mark makes the card ambiguous.
    if (gw < 4 or gh < MIN_GLYPH_HEIGHT or gh * 5 < height * 2
            or gx <= left or gy <= top or gx + gw >= right or gy + gh >= bottom):
        return None
    if any(other is not glyph and other.pixels() * 4 >= glyph.pixels() for other in blobs):
        return None
    return gx, gy, gw, gh


def detect_cards(gray):
    blobs = gray.find_blobs(
        [(WHITE_MIN, 255)], x_stride=3, y_stride=2,
        pixels_threshold=110, area_threshold=MIN_CARD_SIDE * MIN_CARD_SIDE
    )
    cards = []
    for blob in blobs:
        x, y, width, height = blob.rect()
        if (min(width, height) < MIN_CARD_SIDE
                or max(width, height) > 3 * min(width, height)
                or x == 0 or y == 0 or x + width >= DETECT_WIDTH or y + height >= DETECT_HEIGHT
                or blob.pixels() * 2 < width * height):
            continue
        cards.append(blob)

    cards.sort(key=lambda blob: blob.pixels(), reverse=True)
    detections = []
    for card in cards[:MAX_CARDS_PER_FRAME]:
        rect = card.rect()
        glyph = glyph_box(gray, rect)
        if glyph is not None:
            digit = recognize_digit(gray, glyph)
            if digit is not None:
                detections.append((digit, rect, glyph))
    return detections


def center(rect):
    x, y, width, height = rect
    return x + width // 2, y + height // 2


def nearby(previous, current):
    old_x, old_y = center(previous)
    new_x, new_y = center(current)
    return (abs(new_x - old_x) <= max(previous[2], current[2])
            and abs(new_y - old_y) <= max(previous[3], current[3]))


def same_box(first, second):
    x1, y1, w1, h1 = first
    x2, y2, w2, h2 = second
    width = min(x1 + w1, x2 + w2) - max(x1, x2)
    height = min(y1 + h1, y2 + h2) - max(y1, y2)
    return width > 0 and height > 0 and 2 * width * height >= max(w1 * h1, w2 * h2)


class VisionSession:
    def __init__(self, target_id, ticks_diff):
        if type(target_id) is not int or not 0 <= target_id <= 9:
            raise ValueError("INITIAL_TARGET_ID must be an integer from 0 to 9")
        self.target_id = target_id
        self.ticks_diff = ticks_diff
        self.state = "SEARCH"
        self.last_detection = None
        self.last_seen = None
        self.candidate = None
        self.confirm_count = 0

    def target_candidate(self, detections):
        candidate = None
        for detection in detections:
            digit, card, glyph = detection
            if digit != self.target_id:
                continue
            if candidate is None:
                candidate = detection
            elif not (same_box(candidate[1], card) and same_box(candidate[2], glyph)):
                # Independent matches for the same digit are ambiguous.
                return None
        return candidate

    def observe(self, detections, now):
        candidate = self.target_candidate(detections)
        if self.state in ("TRACKING", "HOLD"):
            elapsed = self.ticks_diff(now, self.last_seen)
            if ((self.state == "TRACKING" or elapsed < SHORT_LOSS_MS)
                    and candidate is not None and nearby(self.last_detection[1], candidate[1])):
                return self.track(candidate, now)
            if elapsed < SHORT_LOSS_MS:
                self.state = "HOLD"
                return None
            self.state = "OCCLUDED"

        if candidate is None:
            self.candidate = None
            self.confirm_count = 0
            self.state = "SEARCH" if self.last_seen is None else "OCCLUDED"
            return None

        if self.candidate is not None and nearby(self.candidate[1], candidate[1]):
            self.confirm_count += 1
        else:
            self.confirm_count = 1
        self.candidate = candidate
        if self.confirm_count == CONFIRM_FRAMES:
            self.candidate = None
            self.confirm_count = 0
            return self.track(candidate, now)
        self.state = "CONFIRM" if self.last_seen is None else "REACQUIRE"
        return None

    def track(self, detection, now):
        self.state = "TRACKING"
        self.last_detection = detection
        self.last_seen = now
        return detection


def coordinate_frame(detection):
    if detection is None:
        return NO_TARGET_FRAME
    _, card, glyph = detection
    cx, cy = center(glyph)
    payload = "{},{},{},{},{},{}".format(
        DETECT_WIDTH, DETECT_HEIGHT, cx, cy, card[2], card[3]
    )
    return FRAME_HEADER + payload.encode() + FRAME_TAIL


def send_coordinates(uart, detection):
    frame = coordinate_frame(detection)
    sent = uart.write(frame)
    if sent != len(frame):
        raise OSError("UART2 short write: {} of {}".format(sent, len(frame)))


def draw_overlay(frame, detections, session, selected):
    frame.draw_cross(CENTER_X, CENTER_Y, color=(255, 255, 255))
    for detection in detections:
        digit, card, _ = detection
        color = (0, 255, 0) if detection is selected else (255, 255, 0)
        frame.draw_rectangle(card, color=color, thickness=2)
        frame.draw_string(card[0], max(0, card[1] - 18), str(digit), color=color, scale=2)
    if selected is not None:
        cx, cy = center(selected[2])
        frame.draw_cross(cx, cy, color=(0, 255, 0))
    frame.draw_string(4, 4, "{} {}".format(session.target_id, session.state),
                      color=(255, 255, 255), scale=2)


def cleanup(action, *args):
    try:
        action(*args)
    except Exception as error:
        print("CLEANUP_ERROR", error)


def main():
    import image
    import os
    import time
    from machine import FPIOA, UART
    from media.display import Display
    from media.media import MediaManager
    from media.sensor import Sensor

    session = VisionSession(INITIAL_TARGET_ID, time.ticks_diff)

    uart = sensor = None
    display_ready = media_ready = False
    try:
        fpioa = FPIOA()
        fpioa.set_function(UART2_TX_PIN, FPIOA.UART2_TXD)
        fpioa.set_function(UART2_RX_PIN, FPIOA.UART2_RXD)
        uart = UART(
            UART.UART2, baudrate=115200, bits=UART.EIGHTBITS,
            parity=UART.PARITY_NONE, stop=UART.STOPBITS_ONE
        )

        sensor = Sensor(width=DETECT_WIDTH, height=DETECT_HEIGHT)
        sensor.reset()
        sensor.set_vflip(VFLIP)
        sensor.set_hmirror(HMIRROR)

        sensor.set_framesize(width=DETECT_WIDTH, height=DETECT_HEIGHT)
        sensor.set_pixformat(Sensor.RGB565)

        Display.init(
            Display.VIRT, width=DETECT_WIDTH, height=DETECT_HEIGHT, fps=30, to_ide=True
        )
        display_ready = True
        MediaManager.init()
        media_ready = True
        gray = image.Image(DETECT_WIDTH, DETECT_HEIGHT, image.GRAYSCALE)
        sensor.run()

        last_send = None
        stats_started = time.ticks_ms()
        processed_frames = sent_targets = 0
        print("READY UART2 115200 8N1 TARGET,{}".format(session.target_id))

        while True:
            os.exitpoint()
            frame = sensor.snapshot()
            gray.draw_image(frame, 0, 0)
            detections = detect_cards(gray)
            now = time.ticks_ms()
            previous_state = session.state
            selected = session.observe(detections, now)
            processed_frames += 1

            if (session.state != "HOLD"
                    and (last_send is None or time.ticks_diff(now, last_send) >= SEND_INTERVAL_MS)):
                send_coordinates(uart, selected)
                last_send = time.ticks_ms()
                sent_targets += selected is not None

            if session.state == "TRACKING" and previous_state not in ("TRACKING", "HOLD"):
                print("TRACK,{},{}".format(session.target_id, now))
            elif previous_state in ("TRACKING", "HOLD") and session.state not in ("TRACKING", "HOLD"):
                print("LOST,{},{}".format(session.target_id, now))
            stats_elapsed = time.ticks_diff(now, stats_started)
            if stats_elapsed >= STATS_INTERVAL_MS:
                print("STATS,{},{},{}".format(stats_elapsed, processed_frames, sent_targets))
                stats_started = now
                processed_frames = sent_targets = 0

            draw_overlay(frame, detections, session, selected)
            Display.show_image(frame)

    except KeyboardInterrupt:
        print("STOPPED")
    finally:
        if uart is not None:
            cleanup(send_coordinates, uart, None)
            cleanup(uart.deinit)
        if sensor is not None:
            cleanup(sensor.stop)
        if display_ready:
            cleanup(Display.deinit)
        if media_ready:
            os.exitpoint(os.EXITPOINT_ENABLE_SLEEP)
            time.sleep_ms(100)
            cleanup(MediaManager.deinit)


if __name__ == "__main__":
    main()
