def digit_mask(gray, rect, black_max=BLACK_MAX):
    x, y, width, height = rect
    # Four samples per cell reduce aliasing on thin strokes.
    columns = [
        (x + (4 * column + 1) * width // (4 * DIGIT_COLUMNS),
         x + (4 * column + 3) * width // (4 * DIGIT_COLUMNS))
        for column in range(DIGIT_COLUMNS)
    ]
    rows = []
    pixel = gray.get_pixel
    for row_index in range(DIGIT_ROWS):
        y0 = y + (4 * row_index + 1) * height // (4 * DIGIT_ROWS)
        y1 = y + (4 * row_index + 3) * height // (4 * DIGIT_ROWS)
        mask = 0
        for x0, x1 in columns:
            dark = (pixel(x0, y0) <= black_max) + (pixel(x1, y0) <= black_max)
            dark += (pixel(x0, y1) <= black_max) + (pixel(x1, y1) <= black_max)
            mask = (mask << 1) | (dark >= 2)
        rows.append(mask)
    return rows


def recognize_digit(gray, rect, black_max=BLACK_MAX):
    rows = digit_mask(gray, rect, black_max)
    ratio = rect[2] * 100 // rect[3]
    best_id = None
    best_distance = second_distance = MAX_MATCH_DISTANCE + MIN_MATCH_MARGIN

    for digit, templates in enumerate(DIGIT_TEMPLATES):
        os.exitpoint()
        digit_distance = second_distance
        for template in templates:
            distance = abs(ratio - template[0]) // 3
            for row_index, row in enumerate(rows, 1):
                different = row ^ template[row_index]
                distance += BIT_COUNTS[different & 0xFF] + BIT_COUNTS[different >> 8]
                if distance >= digit_distance:
                    break
            digit_distance = min(distance, digit_distance)

        if digit_distance < best_distance:
            best_id = digit
            second_distance, best_distance = best_distance, digit_distance
        elif digit_distance < second_distance:
            second_distance = digit_distance

    if best_distance <= MAX_MATCH_DISTANCE and second_distance - best_distance >= MIN_MATCH_MARGIN:
        return best_id
    return None


def glyphs_in_card(gray, card, black_max=BLACK_MAX):
    x, y, width, height = card
    inset_x = max(1, width // 12)
    inset_y = max(1, height // 12)
    left, top = x + inset_x, y + inset_y
    right, bottom = x + width - inset_x, y + height - inset_y
    blobs = gray.find_blobs(
        [(0, black_max)], roi=(left, top, right - left, bottom - top),
        x_stride=1, y_stride=1, pixels_threshold=12, area_threshold=24
    )
    if black_max > BLACK_MAX:
        # A brighter cutoff can also pick up background entering the card ROI.
        interior = []
        for blob in blobs:
            gx, gy, gw, gh = blob.rect()
            if gx > left and gy > top and gx + gw < right and gy + gh < bottom:
                interior.append(blob)
        blobs = interior
    if not blobs:
        return []
    largest = max(blob.pixels() for blob in blobs)
    glyphs = []
    for blob in blobs:
        gx, gy, gw, gh = blob.rect()
        if blob.pixels() * 5 < largest:
            continue
        if (gw < 4 or gh < MIN_GLYPH_HEIGHT or gh * 4 < height
                or gx <= left or gy <= top or gx + gw >= right or gy + gh >= bottom):
            return []
        glyphs.append(blob.rect())
    return sorted(glyphs, key=lambda rect: rect[0])


def card_number(gray, glyphs, black_max=BLACK_MAX):
    if len(glyphs) == 1:
        return recognize_digit(gray, glyphs[0], black_max)
    if len(glyphs) != 2:
        return None
    one, zero = glyphs
    gap = zero[0] - (one[0] + one[2])
    if (gap < 0 or gap > max(one[3], zero[3])
            or abs((one[1] + one[3] // 2) - (zero[1] + zero[3] // 2)) > max(one[3], zero[3]) // 3
            or min(one[3], zero[3]) * 2 < max(one[3], zero[3])):
        return None
    if recognize_digit(gray, one, black_max) == 1 and recognize_digit(gray, zero, black_max) == 0:
        return 10
    return None


def card_black_limit(gray, rect):
    x, y, width, height = rect
    samples = sorted(
        gray.get_pixel(x + col * width // 6, y + row * height // 6)
        for row in range(1, 6) for col in range(1, 6)
    )
    background = samples[len(samples) // 2]
    return max(BLACK_MAX, min(110, background * 3 // 5))


def detect_cards(gray):
    blobs = gray.find_blobs(
        [(WHITE_MIN, 255)], x_stride=3, y_stride=2,
        pixels_threshold=110, area_threshold=MIN_CARD_SIDE * MIN_CARD_SIDE
    )
    cards = []
    for blob in blobs:
        x, y, width, height = blob.rect()
        if (min(width, height) < MIN_CARD_SIDE
                or max(width, height) > 3 * min(width, height)
                or blob.pixels() * 2 < width * height):
            continue
        cards.append(blob)
    cards.sort(key=lambda blob: blob.pixels(), reverse=True)
    results = []
    for card in cards[:MAX_CARDS_PER_FRAME]:
        os.exitpoint()
        rect = card.rect()
        glyphs = glyphs_in_card(gray, rect)
        number = card_number(gray, glyphs)
        if number is None:
            black_max = card_black_limit(gray, rect)
            if black_max > BLACK_MAX:
                glyphs = glyphs_in_card(gray, rect, black_max)
                number = card_number(gray, glyphs, black_max)
        if number is not None:
            left = min(x for x, y, w, h in glyphs)
            top = min(y for x, y, w, h in glyphs)
            right = max(x + w for x, y, w, h in glyphs)
            bottom = max(y + h for x, y, w, h in glyphs)
            padding = max(2, (bottom - top) // 20)
            left = max(0, left - padding)
            top = max(0, top - padding)
            right = min(DETECT_WIDTH, right + padding)
            bottom = min(DETECT_HEIGHT, bottom + padding)
            results.append((number, (left, top, right - left, bottom - top)))
    return results


def center(rect):
    x, y, width, height = rect
    return x + width // 2, y + height // 2


def nearby(previous, current):
    old_x, old_y = center(previous)
    new_x, new_y = center(current)
    return (abs(new_x - old_x) <= max(previous[2], current[2])
            and abs(new_y - old_y) <= max(previous[3], current[3]))


class CommandReader:
    def __init__(self):
        self.line = bytearray()
        self.discard = False

    def feed(self, data):
        for value in data or b"":
            if value in (10, 13):
                if self.line and not self.discard:
                    yield bytes(self.line)
                self.line = bytearray()
                self.discard = False
            elif not self.discard:
                if len(self.line) < 8:
                    self.line.append(value)
                else:
                    self.discard = True


class USBCommandInput:
    def __init__(self, stream, poller, pollin):
        self.stream = stream
        self.poller = poller
        self.pollin = pollin

    def __call__(self, limit):
        data = bytearray()
        for _ in range(limit):
            events = self.poller.poll(0)
            if not events or not events[0][1] & self.pollin:
                break
            chunk = self.stream.read(1)
            if not chunk:
                break
            data.extend(chunk.encode() if isinstance(chunk, str) else chunk)
        return data


def open_command_input(uart):
    if COMMAND_INPUT == "none":
        return None
    if COMMAND_INPUT == "uart3":
        if uart is None:
            print("COMMAND_INPUT_ERROR,UART3 unavailable")
            return None
        return uart.read
    if COMMAND_INPUT != "usb":
        raise ValueError("COMMAND_INPUT must be none, uart3 or usb")
    try:
        import sys
        try:
            import select
        except ImportError:
            import uselect as select
        poller = select.poll()
        poller.register(sys.stdin, select.POLLIN)
        return USBCommandInput(sys.stdin, poller, select.POLLIN)
    except (ImportError, AttributeError, OSError, TypeError, ValueError) as error:
        print("COMMAND_INPUT_ERROR,USB", error)
        return None


class VisionSession:
    def __init__(self, ticks_diff, scan_duration_ms=SCAN_DURATION_MS):
        self.ticks_diff = ticks_diff
        self.scan_duration_ms = scan_duration_ms
        self.target_id = None
        self.scan_started = None
        self.seen = set()
        self.streaks = {}
        self.scan_result = None

    def command(self, line, now):
        if line == b"SCAN":
            if self.scan_started is not None:
                return True
            self.scan_started = now
            self.seen.clear()
            self.target_id = None
        elif line == b"STOP":
            self.finish_scan()
            self.target_id = None
        elif line == b"ID,10" or (len(line) == 4 and line[:3] == b"ID," and 48 <= line[3] <= 57):
            target_id = 10 if line == b"ID,10" else line[3] - 48
            if target_id == self.target_id:
                return True
            self.target_id = target_id
            self.finish_scan()
        else:
            return False
        self.streaks = {}
        return True

    def finish_scan(self):
        if self.scan_started is not None:
            self.scan_result = tuple(sorted(self.seen))
            self.scan_started = None

    def take_scan_result(self):
        result = self.scan_result
        self.scan_result = None
        return result

    def observe(self, detections, now):
        if (self.scan_started is not None and self.scan_duration_ms is not None
                and self.ticks_diff(now, self.scan_started) >= self.scan_duration_ms):
            self.finish_scan()

        by_id = {}
        duplicates = set()
        for digit, rect in detections:
            if digit in by_id:
                duplicates.add(digit)
            by_id[digit] = rect

        confirmed = {}
        streaks = {}
        for digit, rect in by_id.items():
            if digit in duplicates:
                continue
            previous = self.streaks.get(digit)
            count = 1
            if previous is not None and (
                (digit == self.target_id and previous[1] == CONFIRM_FRAMES)
                or nearby(previous[0], rect)
            ):
                count = min(CONFIRM_FRAMES, previous[1] + 1)
            streaks[digit] = (rect, count)
            if count == CONFIRM_FRAMES:
                confirmed[digit] = rect
        self.streaks = streaks

        new_ids = ()
        if self.scan_started is not None:
            new_ids = tuple(sorted(set(confirmed) - self.seen))
            self.seen.update(new_ids)
        return confirmed, new_ids, self.take_scan_result()


def coordinate_frame(rect, visible_ids=None):
    if rect is None:
        frame = NO_TARGET_FRAME
    else:
        cx, cy = center(rect)
        payload = "{},{},{},{},{},{}".format(
            DETECT_WIDTH, DETECT_HEIGHT, cx, cy, rect[2], rect[3]
        )
        frame = FRAME_HEADER + payload.encode() + FRAME_TAIL
    if visible_ids is None:
        return frame
    mask = sum(1 << digit for digit in visible_ids)
    return frame[:-len(FRAME_TAIL)] + b"," + str(mask).encode() + FRAME_TAIL


def contest_frame(rect, visible_ids, mode, target_id, sequence):
    payload = coordinate_frame(rect, visible_ids)[:-len(FRAME_TAIL)]
    return payload + ",{},{},{}".format(mode, target_id, sequence).encode() + FRAME_TAIL


class ContestRecorder:
    def __init__(self, root, now, ticks_diff):
        for number in range(1, 10000):
            folder = "{}/gimbal_{:04d}".format(root, number)
            try:
                os.stat(folder)
            except OSError:
                os.mkdir(folder)
                break
        else:
            raise OSError("no free recording directory")
        self.video = open(folder + "/camera.mjpeg", "wb")
        try:
            self.events = open(folder + "/events.csv", "w")
        except BaseException:
            self.video.close()
            raise
        self.started = now
        self.last_frame = None
        self.count = 0
        self.ticks_diff = ticks_diff
        print("[RECORD]", folder)

    def event(self, now, event, value):
        self.events.write("{},{},{}\n".format(self.ticks_diff(now, self.started), event, value))

    def capture(self, frame, now):
        if self.last_frame is not None and self.ticks_diff(now, self.last_frame) < RECORD_PERIOD_MS:
            return
        jpeg = bytes(frame.compressed(quality=75))
        if not jpeg.startswith(b"\xff\xd8") or not jpeg.endswith(b"\xff\xd9"):
            raise ValueError("camera compression did not return JPEG")
        if self.video.write(jpeg) != len(jpeg):
            raise OSError("short recording write")
        self.last_frame = now
        self.count += 1
        self.event(now, "FRAME", self.count)

    def close(self):
        try:
            self.video.close()
        finally:
            self.events.close()


